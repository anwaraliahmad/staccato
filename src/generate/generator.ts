// Procedural shaders, second take.
//
// The 2017 generator (ShaderUtil) grew random trees of sin/cos/log around
// `radius()*time` and displaced vertices along their normals; colors came from
// sin/cos of another tree. Same idea here, with what it was missing:
//   - seeded: a shader is fully described by its seed, so it can be shared;
//   - bounded: every node maps [-1,1] to [-1,1], so shapes don't fly to infinity;
//   - listening: the old version declared getFreqData() and never called it.
//     Every generated shader here is driven by the music.

const ID_PREFIX = 'sn';

/** mulberry32 — tiny, fast, good enough for art. */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const MAX_SEED = 0xfffff;

export function idFromSeed(seed: number): string {
  return `${ID_PREFIX}-${(seed & MAX_SEED).toString(16).padStart(5, '0')}`;
}

export function seedFromId(id: string): number | null {
  const m = /^sn-([0-9a-f]{5})$/.exec(id);
  return m ? parseInt(m[1]!, 16) : null;
}

export function randomSeed(): number {
  return Math.floor(Math.random() * (MAX_SEED + 1));
}

type Rand = () => number;

/** GLSL float literal. */
const f = (n: number) => {
  const s = n.toFixed(3);
  return s.includes('.') ? s : `${s}.`;
};
const pick = <T>(r: Rand, items: readonly T[]): T => items[Math.floor(r() * items.length)]!;

// Leaves are all in [-1, 1].
const LEAVES = ['r', 'a', 'p.x', 'p.y', 'p.z', 'w'] as const;

function expr(r: Rand, depth: number): string {
  if (depth <= 0 || (depth < 3 && r() < 0.25)) {
    const leaf = pick(r, LEAVES);
    // Drifting phase so leaves animate even in silence.
    return r() < 0.35 ? `sin(${leaf}*${f(1 + r() * 6)}+t*${f(0.1 + r() * 0.9)})` : leaf;
  }
  const a = () => expr(r, depth - 1);
  switch (Math.floor(r() * 7)) {
    case 0: return `sin(${f(1 + r() * 5)}*${a()}+${f(r() * 6.283)})`;
    case 1: return `cos(${f(1 + r() * 5)}*${a()}+t*${f(r() * 0.7)})`;
    case 2: return `(${a()}*${a()})`;
    case 3: return `((${a()}+${a()})*.5)`;
    case 4: return `(abs(${a()})*2.-1.)`;
    case 5: return `(fract(${a()}*${f(1 + r() * 3)})*2.-1.)`;
    default: return `mix(${a()},${a()},.5+.5*sin(t*${f(0.1 + r() * 0.5)}))`;
  }
}

// How the music drives the shape. Each returns a non-negative gain.
const AUDIO_GAINS = [
  (r: Rand) => `spectrum(${f(0.05 + r() * 0.4)}+.5*abs(${pick(r, ['r', 'a', 'p.y'])}))*${f(1.2 + r())}`,
  (r: Rand) => `echo(abs(${pick(r, ['a', 'p.x', 'p.z'])}), r*.5+.5)*${f(1.5 + r())}`,
  (r: Rand) => `(.15+bass*${f(1 + r())}+onset*${f(0.3 + r() * 0.5)})`,
  (r: Rand) => `(.1+level*${f(1.5 + r())}+treble*abs(${pick(r, ['p.x', 'p.y', 'a'])}))`,
] as const;

const PALETTES = [
  // The 2017 "darkened fragment shaders": ink on paper.
  (e: string[]) => `vec4(.1*sin(${e[0]}), .1*cos(${e[1]}), .1, 1.0)`,
  // 2016 heart: hot channels from tan/sin of the displacement.
  (e: string[]) => `vec4(.5+.5*sin(${e[0]}), d*1.5, .5+.5*cos(${e[1]}), 1.0)`,
  // Cosine palette.
  (e: string[]) => `vec4(.5+.5*cos(6.283*(${e[0]}*.5+vec3(0.,.33,.67)+d)), 1.0)`,
  (e: string[]) => `vec4(1.0, .5+.5*sin(${e[0]}*3.14+d*4.), .5+.5*cos(${e[1]}), 1.0)`,
] as const;

export interface Generated {
  id: string;
  seed: number;
  note: string;
  vertex: string;
  fragment: string;
}

const COMMON_FUNCS = `// r: distance from centre, a: angle, p: direction, w: wandering phase — all -1..1
float radius(vec2 u) {
	return length(u - .5) * 2.;
}
`;

export function generate(seed: number): Generated {
  seed &= MAX_SEED;
  const r = rng(seed * 2654435761);
  const id = idFromSeed(seed);
  const depth = 3 + Math.floor(r() * 2);
  const shape = expr(r, depth);
  const gain = pick(r, AUDIO_GAINS)(r);
  const amount = 0.12 + r() * 0.25;
  const colorA = expr(r, 2);
  const colorB = expr(r, 2);
  const palette = pick(r, PALETTES)([colorA, colorB]);

  const header = `// ${id} — generated by Staccato from seed 0x${seed.toString(16)}
// Press "+" for another, or edit me (E).
`;

  const vertex = `${header}
varying vec2 vUv;
varying vec3 vP;
varying float d; // displacement, roughly 0..1

${COMMON_FUNCS}
void main() {
	vUv = uv;
	vP = normalize(position + vec3(1e-4));
	vec3 p = vP;
	float r = clamp(radius(uv), 0., 1.) * 2. - 1.;
	float a = atan(p.z, p.x) / 3.14159;
	float t = time;
	float w = sin(t * .3 + r * 2.);

	float shape = ${shape};
	d = clamp(shape * .5 + .5, 0., 1.) * ${gain};

	vec3 newposition = position + normal * d * size * ${f(amount)};
	gl_Position = projectionMatrix * modelViewMatrix * vec4(newposition, 1.0);
}
`;

  const fragment = `${header}
varying vec2 vUv;
varying vec3 vP;
varying float d;

${COMMON_FUNCS}
void main() {
	vec3 p = vP;
	float r = clamp(radius(vUv), 0., 1.) * 2. - 1.;
	float a = atan(p.z, p.x) / 3.14159;
	float t = time;
	float w = sin(t * .3 + r * 2.);
	gl_FragColor = ${palette};
}
`;

  return { id, seed, note: `Generated from seed 0x${seed.toString(16)}.`, vertex, fragment };
}
